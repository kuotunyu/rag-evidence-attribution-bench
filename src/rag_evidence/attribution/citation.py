"""Direct-citation attribution: the passages the model itself cited.

Mode B only. In teacher-forced mode there is no citation act to read off — the gold
answer was never generated by the model, and substituting a post-hoc self-citation
prompt would be a different method with different failure modes. The runner reports
this method as unsupported under mode A (`null` in gold-mode tables).
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

from rag_evidence.attribution.base import AttributionMethod, AttributionResult, ModelResources
from rag_evidence.attribution.registry import register
from rag_evidence.data.schema import Passage
from rag_evidence.errors import UpstreamMissingError


@register
class CitationAttribution(AttributionMethod):
    name = "citations"
    supports_teacher_forced = False

    def attribute(
        self,
        question: str,
        passages: Sequence[Passage],
        target_answer: str,
        model: ModelResources | None,
        method_config: Mapping[str, Any],
    ) -> AttributionResult:
        generation_record = method_config.get("generation_record")
        if generation_record is None:
            raise UpstreamMissingError("citations method needs the sample's generation record")
        cited = set(generation_record["cited_passage_ids"] or [])
        raw = {p.passage_id: (1.0 if p.passage_id in cited else 0.0) for p in passages}
        return AttributionResult(
            raw_scores=raw,
            metadata={
                "citation_order": list(generation_record["citations_raw"] or []),
                "invalid_citations": list(generation_record["invalid_citations"] or []),
            },
            num_model_calls=0,
        )
