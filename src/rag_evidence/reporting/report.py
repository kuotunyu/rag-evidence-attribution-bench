def build_report(cfg: AppConfig) -> None:
    summary_path = cfg.results_derived_dir / "summary.json"
    summary = read_json(summary_path) if summary_path.exists() else None

    real_summary: dict[str, Any] | None = None
    excluded: list[str] = []
    if summary is not None:
        real_summary, excluded = _real_only(summary)
        if not real_summary.get("splits"):
            real_summary = None

    block = render_results_block(real_summary)

    report_path = cfg.results_derived_dir / "report.md"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    if cfg.execution.track == "challenge":
        lines = [
            "# Human-gated challenge report",
            "",
            f"Phase: `{cfg.execution.phase}`; variant: `{cfg.execution.variant}`.",
            "",
            "Sibling variants and natural-benchmark rows are intentionally not pooled.",
            "",
            block,
            "",
        ]
    else:
        lines = ["# Benchmark report", "", block, ""]
    if excluded:
        lines += [
            "## Excluded from this report",
            "",
            "Mock-backend runs (tests / pipeline verification), never reported as results:",
            "",
            *[f"- `{p}` (execution_kind: mock)" for p in sorted(excluded)],
            "",
        ]
    report_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    logger.info("wrote %s", report_path)

    figures: list[Path] = []
    if real_summary is not None:
        figures = _write_figures(cfg, real_summary)
        for f in figures:
            logger.info("wrote %s", f)

    if cfg.execution.track == "challenge":
        return
    readme_blocks = {
        Path("README.md"): render_results_block(real_summary, locale="zh-TW"),
        Path("README_en.md"): block,
    }
    for readme, readme_block in readme_blocks.items():
        if inject_into_readme(readme, readme_block):
            logger.info("updated results block in %s", readme)
