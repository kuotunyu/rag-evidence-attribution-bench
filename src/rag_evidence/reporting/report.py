"""The `report` stage.

Integrity rules enforced here:
- every number comes from results/derived/summary.json (which `evaluate` derives from
  raw records) — nothing is typed by hand;
- runs with execution_kind == "mock" (fake backend) are structurally excluded from the
  README and figures; report.md lists them as excluded;
- when no real data exists for a metric family, the README carries a machine-generated
  PENDING line produced by this same code path — pending and real states share one
  mechanism.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any

from rag_evidence.config import AppConfig
from rag_evidence.storage.artifacts import read_json

logger = logging.getLogger(__name__)

BEGIN_MARK = "<!-- BEGIN AUTOGENERATED RESULTS -->"
END_MARK = "<!-- END AUTOGENERATED RESULTS -->"

_SPLIT_ORDER = ("smoke", "dev", "eval")


def _fmt(x: Any, nd: int = 3) -> str:
    if x is None:
        return "—"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def _is_real(entry: dict[str, Any]) -> bool:
    return bool(entry.get("execution_kind", "real") != "mock")


def attribution_legacy_view(entry: dict[str, Any]) -> dict[str, Any]:
    """Expose a flattened read-only view for schema-v1 report consumers."""
    if entry.get("schema_version") != 2:
        return entry
    agreement = entry["agreement"]
    causal = entry["causal_dependence"]
    execution = entry["execution"]
    legacy = dict(entry.get("legacy_v1") or {})
    legacy.update(
        {
            "run": entry["run"],
            "execution_kind": entry["execution_kind"],
            "partial": entry["partial"],
            "device": entry["device"],
            "method": entry["method"],
            "run_namespace": entry.get("run_namespace"),
            "generation_run": entry.get("generation_run"),
            "is_control": entry["is_control"],
            "prf_at": agreement["prf_at"],
            "auprc": agreement["mean_average_precision"],
            "ndcg_at_10": agreement["ndcg_at_10"],
            "n_agreement": agreement["n"],
            "sufficiency": causal["sufficiency_mean"],
            "comprehensiveness": causal["comprehensiveness_mean"],
            "n_faithfulness": causal["n"],
            **execution,
        }
    )
    return legacy


def _real_only(summary: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Strip mock entries; return (filtered summary, list of excluded run paths)."""
    excluded: list[str] = []
    filtered: dict[str, Any] = {**summary, "splits": {}}
    for split, payload in summary.get("splits", {}).items():
        new_payload: dict[str, Any] = {"n_questions": payload.get("n_questions")}
        retrieval = {m: e for m, e in payload.get("retrieval", {}).items() if _is_real(e)}
        excluded += [
            e.get("run", f"{split}/retrieve/{m}")
            for m, e in payload.get("retrieval", {}).items()
            if not _is_real(e)
        ]
        generation = {m: e for m, e in payload.get("generation", {}).items() if _is_real(e)}
        excluded += [
            e.get("run", f"{split}/generate/{m}")
            for m, e in payload.get("generation", {}).items()
            if not _is_real(e)
        ]
        attribution: dict[str, Any] = {}
        for mode, methods in payload.get("attribution", {}).items():
            kept: dict[str, Any] = {}
            for name, entry in methods.items():
                if not isinstance(entry, dict) or "run" not in entry:
                    kept[name] = entry  # subset / generation_run metadata blocks
                    continue
                if _is_real(entry):
                    kept[name] = entry
                else:
                    excluded.append(entry.get("run", f"{split}/attribute/{mode}/{name}"))
            if any(isinstance(v, dict) and "run" in v for v in kept.values()):
                attribution[mode] = kept
        if retrieval or generation or attribution:
            new_payload.update(retrieval=retrieval, generation=generation, attribution=attribution)
            filtered["splits"][split] = new_payload
    return filtered, excluded


# ------------------------------------------------------------------------ md tables


def _retrieval_table(splits: dict[str, Any]) -> str:
    rows = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for method, e in sorted(payload.get("retrieval", {}).items()):
            label = f"{method} ({e.get('device', 'cpu')})"
            if e.get("partial"):
                label += " ⚠partial"
            rows.append(
                f"| {split} | {label} | {_fmt(e['recall_at'].get('2'))} | "
                f"{_fmt(e['recall_at'].get('5'))} | {_fmt(e['mrr'])} | "
                f"{_fmt(e['ndcg_at_10'])} | {_fmt(e['latency_ms']['p50'], 1)} | "
                f"{e['n_evaluated']} |"
            )
    if not rows:
        return "_Retrieval results: **PENDING** — no real retrieval run evaluated yet._"
    header = (
        "| split | method | R@2 | R@5 | MRR | nDCG@10 | p50 ms | n |\n"
        "|---|---|---|---|---|---|---|---|"
    )
    return "**Retrieval**\n\n" + header + "\n" + "\n".join(rows)


def _generation_table(splits: dict[str, Any]) -> str:
    rows = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for name, e in sorted(payload.get("generation", {}).items()):
            cit = e["citation"]
            model = e.get("model", {})
            dtype = model.get("dtype_effective", "?")
            if e.get("partial"):
                name += " ⚠partial"
            rows.append(
                f"| {split} | {name} ({dtype}) | {_fmt(e['em'])} | {_fmt(e['f1'])} | "
                f"{_fmt(cit['precision'])} | {_fmt(cit['recall'])} | {_fmt(cit['f1'])} | "
                f"{_fmt(e['abstain_rate'])} | {_fmt(e['throughput_tokens_per_s'], 1)} | "
                f"{_fmt(e['peak_vram_mb'], 0)} | {e['n_evaluated']} |"
            )
    if not rows:
        return (
            "_Generation results: **PENDING** — run `notebooks/00_colab_smoke.ipynb` on a "
            "GPU runtime, then `import-results` + `evaluate` + `report`._"
        )
    header = (
        "| split | model | EM | F1 | cite-P | cite-R | cite-F1 | abstain | tok/s | "
        "peak VRAM MB | n |\n|---|---|---|---|---|---|---|---|---|---|---|"
    )
    return "**Generation** (deterministic greedy)\n\n" + header + "\n" + "\n".join(rows)


def _has_v2_attribution(splits: dict[str, Any]) -> bool:
    return any(
        isinstance(entry, dict) and entry.get("schema_version") == 2
        for payload in splits.values()
        for methods in payload.get("attribution", {}).values()
        if isinstance(methods, dict)
        for entry in methods.values()
    )


def _paired_comparison_table(methods: dict[str, Any]) -> str:
    rows: list[str] = []
    exclusion_order = (
        "candidate_missing",
        "comparator_missing",
        "candidate_null",
        "comparator_null",
    )
    for name, comparison in sorted((methods.get("paired_comparisons") or {}).items()):
        for metric_name, metric in sorted(comparison.get("metrics", {}).items()):
            effect = "—"
            if metric.get("mean_delta") is not None:
                effect = (
                    f"{_fmt(metric['mean_delta'])} "
                    f"[{_fmt(metric.get('ci_low'))}, {_fmt(metric.get('ci_high'))}]"
                )
            exclusions = metric.get("exclusions") or {}
            exclusion_text = ", ".join(f"{key}={exclusions.get(key, 0)}" for key in exclusion_order)
            rows.append(
                f"| {name} | {comparison.get('analysis_tier')} | {metric_name} | "
                f"{effect} | {metric.get('n_pairs')} | {exclusion_text} | "
                f"{metric.get('favorable_direction')} |"
            )
    if not rows:
        return "_Paired comparisons: **NOT RUN**._"
    header = (
        "| comparison | tier | metric | delta 95% CI | n_pairs | exclusions | favorable |\n"
        "|---|---|---|---|---|---|---|"
    )
    return "**Paired comparisons**\n\n" + header + "\n" + "\n".join(rows)


def _attribution_tables_v2(splits: dict[str, Any], primary_k: int) -> str:
    blocks: list[str] = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for mode in ("gold", "generated"):
            methods = payload.get("attribution", {}).get(mode)
            if not methods:
                continue
            title = (
                f"**Attribution — mode A (teacher-forced gold answer), split `{split}`**"
                if mode == "gold"
                else f"**Attribution — mode B (generated answer), split `{split}`**"
            )
            subset_line = ""
            subset = methods.get("subset")
            if mode == "generated" and isinstance(subset, dict):
                subset_line = (
                    f"\n_Agreement metrics use the correct-answer subset: "
                    f"n_correct={subset['n_correct']} of n_total={subset['n_total']} "
                    f"(criterion: {subset['criterion']}; abstained: {subset['n_abstained']})._\n"
                )
            header = (
                f"| method | F1@{primary_k} | MAP | nDCG@10 | sufficiency diagnostic ↓ | "
                "comprehensiveness diagnostic ↑ | n agreement | n causal | s/sample | fail % |\n"
                "|---|---|---|---|---|---|---|---|---|---|"
            )
            rows: list[str] = []
            for name in sorted(
                (
                    name
                    for name, entry in methods.items()
                    if isinstance(entry, dict) and entry.get("schema_version") == 2
                ),
                key=lambda value: (bool(methods[value].get("is_control")), value),
            ):
                entry = methods[name]
                agreement = entry["agreement"]
                causal = entry["causal_dependence"]
                execution = entry["execution"]
                label = f"{name} _(control)_" if entry.get("is_control") else name
                if entry.get("partial"):
                    label += " ⚠partial"
                prf = agreement["prf_at"].get(str(primary_k), {})
                rows.append(
                    f"| {label} | {_fmt(prf.get('f1'))} | "
                    f"{_fmt(agreement['mean_average_precision'])} | "
                    f"{_fmt(agreement['ndcg_at_10'])} | "
                    f"{_fmt(causal['sufficiency_mean'])} | "
                    f"{_fmt(causal['comprehensiveness_mean'])} | {agreement['n']} | "
                    f"{causal['n']} | {_fmt(execution['seconds_per_sample'])} | "
                    f"{_fmt(100 * execution['failure_rate'], 1)} |"
                )
            validation = methods.get("causal_validation") or {
                "status": "not_run",
                "missing_methods": [],
            }
            status = str(validation.get("status", "not_run")).replace("_", " ").upper()
            missing = validation.get("missing_methods") or []
            missing_text = f" Missing methods: {', '.join(missing)}." if missing else ""
            validation_line = (
                f"Construct validation: **{status}**.{missing_text} "
                "Sufficiency and comprehensiveness remain diagnostics unless this status passes."
            )
            blocks.append(
                title
                + subset_line
                + "\n"
                + header
                + "\n"
                + "\n".join(rows)
                + "\n\n"
                + validation_line
                + "\n\n"
                + _paired_comparison_table(methods)
            )
    if not blocks:
        return "_Attribution results: **PENDING**._"
    return "\n\n".join(blocks)


def _attribution_tables(splits: dict[str, Any], primary_k: int) -> str:
    if _has_v2_attribution(splits):
        return _attribution_tables_v2(splits, primary_k)
    blocks: list[str] = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for mode in ("gold", "generated"):
            methods = payload.get("attribution", {}).get(mode)
            if not methods:
                continue
            title = (
                f"**Attribution — mode A (teacher-forced gold answer), split `{split}`**"
                if mode == "gold"
                else f"**Attribution — mode B (generated answer), split `{split}`**"
            )
            subset_line = ""
            subset = methods.get("subset")
            if mode == "generated" and isinstance(subset, dict):
                subset_line = (
                    f"\n_Agreement metrics over the correct subset only: "
                    f"n_correct={subset['n_correct']} of n_total={subset['n_total']} "
                    f"(criterion: {subset['criterion']}; abstained: {subset['n_abstained']})._\n"
                )
            header = (
                f"| method | F1@{primary_k} | AUPRC | nDCG@10 | sufficiency ↓ | "
                "comprehensiveness ↑ | s/sample | fail % | n |\n"
                "|---|---|---|---|---|---|---|---|---|"
            )
            rows = []
            for name in sorted(
                (n for n, e in methods.items() if isinstance(e, dict) and "run" in e),
                key=lambda n: (n.startswith("control_"), n),
            ):
                e = methods[name]
                label = f"{name} _(control)_" if e.get("is_control") else name
                if e.get("partial"):
                    label += " ⚠partial"
                prf = e["prf_at"].get(str(primary_k), {})
                rows.append(
                    f"| {label} | {_fmt(prf.get('f1'))} | {_fmt(e['auprc'])} | "
                    f"{_fmt(e['ndcg_at_10'])} | {_fmt(e['sufficiency'])} | "
                    f"{_fmt(e['comprehensiveness'])} | {_fmt(e['seconds_per_sample'])} | "
                    f"{_fmt(100 * e['failure_rate'], 1)} | {e['n_agreement']} |"
                )
            blocks.append(title + subset_line + "\n" + header + "\n" + "\n".join(rows))
    if not blocks:
        return (
            "_Attribution results: **PENDING** — GPU attribution runs happen on Colab "
            "(`notebooks/00_colab_smoke.ipynb`)._"
        )
    return "\n\n".join(blocks)


def render_results_block(summary: dict[str, Any] | None, *, locale: str = "en") -> str:
    if not summary or not summary.get("splits"):
        if locale == "zh-TW":
            return (
                "**結果待產生** — 尚未匯入經驗證的 benchmark run。\n"
                "請在 Colab 執行 `notebooks/00_colab_smoke.ipynb`, 再執行 "
                "`python -m rag_evidence.cli import-results …`。"
            )
        return (
            "**RESULTS PENDING** — no verified benchmark run has been imported yet.\n"
            "Run `notebooks/00_colab_smoke.ipynb` on Colab, then "
            "`python -m rag_evidence.cli import-results …`."
        )
    source_snapshot = summary.get("source_snapshot_utc") or summary.get("generated_utc")
    footer = (
        f"_Generated by `report` from the configured derived `summary.json` at "
        f"source snapshot {source_snapshot} (package {summary.get('package_version')}; "
        f"dataset sha256:{str(summary.get('dataset_hash'))[:12]}…). Do not edit by hand._"
    )
    if locale == "zh-TW":
        footer = (
            f"_由 `report` 根據設定的 derived `summary.json` 與 "
            f"來源快照 {source_snapshot} 自動產生 (package "
            f"{summary.get('package_version')}; dataset sha256:"
            f"{str(summary.get('dataset_hash'))[:12]}…)。請勿手動編輯。_"
        )
    parts = [
        _retrieval_table(summary["splits"]),
        _generation_table(summary["splits"]),
        _attribution_tables(summary["splits"], summary.get("primary_k", 2)),
        footer,
    ]
    block = "\n\n".join(parts)
    if locale == "zh-TW":
        block = (
            block.replace("**Retrieval**", "**Retrieval 檢索結果**")
            .replace(
                "**Generation** (deterministic greedy)",
                "**Generation 生成結果** (deterministic greedy)",
            )
            .replace(
                "**Attribution — mode A (teacher-forced gold answer), split",
                "**Attribution — mode A (teacher-forced gold answer), split",
            )
            .replace(
                "**Attribution — mode B (generated answer), split",
                "**Attribution — mode B (generated answer), split",
            )
            .replace(
                "_Agreement metrics over the correct subset only:",
                "_Agreement metrics 僅在答對子集計算:",
            )
        )
    return block


def inject_into_readme(readme_path: Path, block: str) -> bool:
    if not readme_path.exists():
        logger.warning("README %s not found — skipping injection", readme_path)
        return False
    text = readme_path.read_text(encoding="utf-8")
    if BEGIN_MARK not in text or END_MARK not in text:
        logger.warning("markers missing in %s — skipping injection", readme_path)
        return False
    pattern = re.compile(re.escape(BEGIN_MARK) + r".*?" + re.escape(END_MARK), flags=re.DOTALL)
    new_text = pattern.sub(BEGIN_MARK + "\n" + block + "\n" + END_MARK, text)
    readme_path.write_text(new_text, encoding="utf-8", newline="\n")
    return True


