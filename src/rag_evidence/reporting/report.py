"""The `report` stage.

Integrity rules enforced here:
- every number comes from results/derived/summary.json (which `evaluate` derives from
  raw records) — nothing is typed by hand;
- runs with execution_kind == "mock" (fake backend) are structurally excluded from the
  README and figures; report.md lists them as excluded;
- when no real data exists for a metric family, the README carries a machine-generated
  PENDING line produced by this same code path — pending and real states share one
  mechanism.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any

from rag_evidence.config import AppConfig
from rag_evidence.storage.artifacts import read_json

logger = logging.getLogger(__name__)

BEGIN_MARK = "<!-- BEGIN AUTOGENERATED RESULTS -->"
END_MARK = "<!-- END AUTOGENERATED RESULTS -->"

_SPLIT_ORDER = ("smoke", "dev", "eval")


def _fmt(x: Any, nd: int = 3) -> str:
    if x is None:
        return "—"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def _is_real(entry: dict[str, Any]) -> bool:
    return bool(entry.get("execution_kind", "real") != "mock")


def _real_only(summary: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Strip mock entries; return (filtered summary, list of excluded run paths)."""
    excluded: list[str] = []
    filtered: dict[str, Any] = {**summary, "splits": {}}
    for split, payload in summary.get("splits", {}).items():
        new_payload: dict[str, Any] = {"n_questions": payload.get("n_questions")}
        retrieval = {m: e for m, e in payload.get("retrieval", {}).items() if _is_real(e)}
        excluded += [
            e.get("run", f"{split}/retrieve/{m}")
            for m, e in payload.get("retrieval", {}).items()
            if not _is_real(e)
        ]
        generation = {m: e for m, e in payload.get("generation", {}).items() if _is_real(e)}
        excluded += [
            e.get("run", f"{split}/generate/{m}")
            for m, e in payload.get("generation", {}).items()
            if not _is_real(e)
        ]
        attribution: dict[str, Any] = {}
        for mode, methods in payload.get("attribution", {}).items():
            kept: dict[str, Any] = {}
            for name, entry in methods.items():
                if not isinstance(entry, dict) or "run" not in entry:
                    kept[name] = entry  # subset / generation_run metadata blocks
                    continue
                if _is_real(entry):
                    kept[name] = entry
                else:
                    excluded.append(entry.get("run", f"{split}/attribute/{mode}/{name}"))
            if any(isinstance(v, dict) and "run" in v for v in kept.values()):
                attribution[mode] = kept
        if retrieval or generation or attribution:
            new_payload.update(retrieval=retrieval, generation=generation, attribution=attribution)
            filtered["splits"][split] = new_payload
    return filtered, excluded


# ------------------------------------------------------------------------ md tables


def _retrieval_table(splits: dict[str, Any]) -> str:
    rows = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for method, e in sorted(payload.get("retrieval", {}).items()):
            label = f"{method} ({e.get('device', 'cpu')})"
            if e.get("partial"):
                label += " ⚠partial"
            rows.append(
                f"| {split} | {label} | {_fmt(e['recall_at'].get('2'))} | "
                f"{_fmt(e['recall_at'].get('5'))} | {_fmt(e['mrr'])} | "
                f"{_fmt(e['ndcg_at_10'])} | {_fmt(e['latency_ms']['p50'], 1)} | "
                f"{e['n_evaluated']} |"
            )
    if not rows:
        return "_Retrieval results: **PENDING** — no real retrieval run evaluated yet._"
    header = (
        "| split | method | R@2 | R@5 | MRR | nDCG@10 | p50 ms | n |\n"
        "|---|---|---|---|---|---|---|---|"
    )
    return "**Retrieval**\n\n" + header + "\n" + "\n".join(rows)


def _generation_table(splits: dict[str, Any]) -> str:
    rows = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for name, e in sorted(payload.get("generation", {}).items()):
            cit = e["citation"]
            model = e.get("model", {})
            dtype = model.get("dtype_effective", "?")
            if e.get("partial"):
                name += " ⚠partial"
            rows.append(
                f"| {split} | {name} ({dtype}) | {_fmt(e['em'])} | {_fmt(e['f1'])} | "
                f"{_fmt(cit['precision'])} | {_fmt(cit['recall'])} | {_fmt(cit['f1'])} | "
                f"{_fmt(e['abstain_rate'])} | {_fmt(e['throughput_tokens_per_s'], 1)} | "
                f"{_fmt(e['peak_vram_mb'], 0)} | {e['n_evaluated']} |"
            )
    if not rows:
        return (
            "_Generation results: **PENDING** — run `notebooks/00_colab_smoke.ipynb` on a "
            "GPU runtime, then `import-results` + `evaluate` + `report`._"
        )
    header = (
        "| split | model | EM | F1 | cite-P | cite-R | cite-F1 | abstain | tok/s | "
        "peak VRAM MB | n |\n|---|---|---|---|---|---|---|---|---|---|---|"
    )
    return "**Generation** (deterministic greedy)\n\n" + header + "\n" + "\n".join(rows)


def _attribution_tables(splits: dict[str, Any], primary_k: int) -> str:
    blocks: list[str] = []
    for split in _SPLIT_ORDER:
        payload = splits.get(split)
        if not payload:
            continue
        for mode in ("gold", "generated"):
            methods = payload.get("attribution", {}).get(mode)
            if not methods:
                continue
            title = (
                f"**Attribution — mode A (teacher-forced gold answer), split `{split}`**"
                if mode == "gold"
                else f"**Attribution — mode B (generated answer), split `{split}`**"
            )
            subset_line = ""
            subset = methods.get("subset")
            if mode == "generated" and isinstance(subset, dict):
                subset_line = (
                    f"\n_Agreement metrics over the correct subset only: "
                    f"n_correct={subset['n_correct']} of n_total={subset['n_total']} "
                    f"(criterion: {subset['criterion']}; abstained: {subset['n_abstained']})._\n"
                )
            header = (
                f"| method | F1@{primary_k} | AUPRC | nDCG@10 | sufficiency ↓ | "
                "comprehensiveness ↑ | s/sample | fail % | n |\n"
                "|---|---|---|---|---|---|---|---|---|"
            )
            rows = []
            for name in sorted(
                (n for n, e in methods.items() if isinstance(e, dict) and "run" in e),
                key=lambda n: (n.startswith("control_"), n),
            ):
                e = methods[name]
                label = f"{name} _(control)_" if e.get("is_control") else name
                if e.get("partial"):
                    label += " ⚠partial"
                prf = e["prf_at"].get(str(primary_k), {})
                rows.append(
                    f"| {label} | {_fmt(prf.get('f1'))} | {_fmt(e['auprc'])} | "
                    f"{_fmt(e['ndcg_at_10'])} | {_fmt(e['sufficiency'])} | "
                    f"{_fmt(e['comprehensiveness'])} | {_fmt(e['seconds_per_sample'])} | "
                    f"{_fmt(100 * e['failure_rate'], 1)} | {e['n_agreement']} |"
                )
            blocks.append(title + subset_line + "\n" + header + "\n" + "\n".join(rows))
    if not blocks:
        return (
            "_Attribution results: **PENDING** — GPU attribution runs happen on Colab "
            "(`notebooks/00_colab_smoke.ipynb`)._"
        )
    return "\n\n".join(blocks)


def render_results_block(summary: dict[str, Any] | None) -> str:
    if not summary or not summary.get("splits"):
        return (
            "**RESULTS PENDING** — no verified benchmark run has been imported yet.\n"
            "Run `notebooks/00_colab_smoke.ipynb` on Colab, then "
            "`python -m rag_evidence.cli import-results …`."
        )
    parts = [
        _retrieval_table(summary["splits"]),
        _generation_table(summary["splits"]),
        _attribution_tables(summary["splits"], summary.get("primary_k", 2)),
        (
            f"_Generated by `report` from `results/derived/summary.json` at "
            f"{summary.get('generated_utc')} (package {summary.get('package_version')}; "
            f"dataset sha256:{str(summary.get('dataset_hash'))[:12]}…). Do not edit by hand._"
        ),
    ]
    return "\n\n".join(parts)


def inject_into_readme(readme_path: Path, block: str) -> bool:
    if not readme_path.exists():
        logger.warning("README %s not found — skipping injection", readme_path)
        return False
    text = readme_path.read_text(encoding="utf-8")
    if BEGIN_MARK not in text or END_MARK not in text:
        logger.warning("markers missing in %s — skipping injection", readme_path)
        return False
    pattern = re.compile(re.escape(BEGIN_MARK) + r".*?" + re.escape(END_MARK), flags=re.DOTALL)
    new_text = pattern.sub(BEGIN_MARK + "\n" + block + "\n" + END_MARK, text)
    readme_path.write_text(new_text, encoding="utf-8", newline="\n")
    return True


# -------------------------------------------------------------------------- figures


def _write_figures(cfg: AppConfig, summary: dict[str, Any]) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    assets = Path(cfg.paths.assets_dir)
    assets.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for split, payload in summary.get("splits", {}).items():
        retrieval = payload.get("retrieval", {})
        if retrieval:
            methods = sorted(retrieval)
            metrics = ["recall_at.2", "mrr", "ndcg_at_10"]
            labels = ["Recall@2", "MRR", "nDCG@10"]
            fig, ax = plt.subplots(figsize=(6, 3.2))
            width = 0.8 / len(methods)
            for i, method in enumerate(methods):
                e = retrieval[method]
                vals = [e["recall_at"].get("2"), e["mrr"], e["ndcg_at_10"]]
                xs = [j + i * width for j in range(len(metrics))]
                ax.bar(xs, [v or 0 for v in vals], width=width, label=method)
            ax.set_xticks([j + 0.4 - width / 2 for j in range(len(metrics))])
            ax.set_xticklabels(labels)
            ax.set_ylim(0, 1.0)
            ax.set_title(f"Retrieval — split {split} (n={payload.get('n_questions')})")
            ax.legend(fontsize=8)
            fig.tight_layout()
            out = assets / f"retrieval_{split}.png"
            fig.savefig(out, dpi=150)
            plt.close(fig)
            written.append(out)

        for mode, methods_d in payload.get("attribution", {}).items():
            entries = {n: e for n, e in methods_d.items() if isinstance(e, dict) and "run" in e}
            if not entries:
                continue
            names = sorted(entries, key=lambda n: (n.startswith("control_"), n))
            f1s = [
                entries[n]["prf_at"].get(str(summary.get("primary_k", 2)), {}).get("f1") or 0
                for n in names
            ]
            fig, ax = plt.subplots(figsize=(6, 0.5 + 0.4 * len(names)))
            ax.barh(range(len(names)), f1s)
            ax.set_yticks(range(len(names)))
            ax.set_yticklabels(names, fontsize=8)
            ax.invert_yaxis()
            ax.set_xlim(0, 1.0)
            ax.set_xlabel(f"F1@{summary.get('primary_k', 2)} vs supporting facts")
            ax.set_title(f"Attribution ({mode}) — split {split}")
            fig.tight_layout()
            out = assets / f"attribution_{split}_{mode}.png"
            fig.savefig(out, dpi=150)
            plt.close(fig)
            written.append(out)
    return written


# --------------------------------------------------------------------------- driver


def build_report(cfg: AppConfig) -> None:
    summary_path = cfg.results_derived_dir / "summary.json"
    summary = read_json(summary_path) if summary_path.exists() else None

    real_summary: dict[str, Any] | None = None
    excluded: list[str] = []
    if summary is not None:
        real_summary, excluded = _real_only(summary)
        if not real_summary.get("splits"):
            real_summary = None

    block = render_results_block(real_summary)

    report_path = cfg.results_derived_dir / "report.md"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Benchmark report", "", block, ""]
    if excluded:
        lines += [
            "## Excluded from this report",
            "",
            "Mock-backend runs (tests / pipeline verification), never reported as results:",
            "",
            *[f"- `{p}` (execution_kind: mock)" for p in sorted(excluded)],
            "",
        ]
    report_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    logger.info("wrote %s", report_path)

    figures: list[Path] = []
    if real_summary is not None:
        figures = _write_figures(cfg, real_summary)
        for f in figures:
            logger.info("wrote %s", f)

    for readme in (Path("README.md"), Path("README_zh-TW.md")):
        if inject_into_readme(readme, block):
            logger.info("updated results block in %s", readme)
