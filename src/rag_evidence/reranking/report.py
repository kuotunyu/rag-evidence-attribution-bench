def _verify_locked_analysis_file(path_value: str, expected: str, label: str) -> str:
    path = Path(path_value)
    if not path.exists():
        raise ConfigError(f"{label} file is missing: {path}")
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != expected:
        raise ConfigError(f"{label} hash mismatch for {path}: expected {expected}, got {actual}")
    return actual


def _mean(values: Iterable[float | None]) -> float | None:
    usable = [float(v) for v in values if v is not None]
    return sum(usable) / len(usable) if usable else None


